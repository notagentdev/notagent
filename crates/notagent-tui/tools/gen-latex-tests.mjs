#!/usr/bin/env node
// Generates the table-driven part of `tests/latex.rs` from
// `packages/tui/test/latex.test.ts`.
//
// The five `defineCases([...])` tables hold 200+ (source, expected) pairs; they
// are evaluated here so no pair can be mistyped.

import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "/Users/dev/projects/notagent-main/packages/tui/test/latex.test.ts";
const OUTPUT = new URL("../tests/latex_cases.rs", import.meta.url);

const source = readFileSync(SOURCE, "utf8");

/** Every `describe("...", () => { defineCases([...]) })` block. */
function tables() {
	const result = [];
	const describePattern = /describe\("([^"]+)", \(\) => \{\s*defineCases\(\[/g;
	let match = describePattern.exec(source);
	while (match) {
		const start = source.indexOf("[", match.index + match[0].length - 1);
		let depth = 0;
		let end = -1;
		let inString = null;
		for (let index = start; index < source.length; index++) {
			const character = source[index];
			if (inString) {
				if (character === "\\" && inString !== "`raw") index++;
				else if (character === inString) inString = null;
				continue;
			}
			if (character === '"' || character === "'" || character === "`") {
				inString = character;
				continue;
			}
			if (character === "[") depth++;
			if (character === "]") {
				depth--;
				if (depth === 0) {
					end = index;
					break;
				}
			}
		}
		const text = source.slice(start, end + 1);
		// eslint-disable-next-line no-eval
		const cases = eval(`(function () { const String = globalThis.String; return ${text}; })()`);
		result.push({ title: match[1], cases });
		match = describePattern.exec(source);
	}
	return result;
}

function rustString(value) {
	return JSON.stringify(value);
}

function identifier(title) {
	return title
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, "_")
		.replace(/^_+|_+$/g, "");
}

const blocks = tables().map(({ title, cases }) => {
	const entries = cases
		.map(([input, expected]) => `    (${rustString(input)}, ${rustString(expected)}),`)
		.join("\n");
	return `/// \`describe("${title}")\`\npub static ${identifier(title).toUpperCase()}: &[(&str, &str)] = &[\n${entries}\n];\n`;
});

writeFileSync(
	OUTPUT,
	`//! GENERATED by \`tools/gen-latex-tests.mjs\` — do not edit.\n//!\n//! The \`defineCases\` tables of \`packages/tui/test/latex.test.ts\`.\n\n${blocks.join("\n")}`,
);
console.log(`wrote ${OUTPUT.pathname}`);
