#!/usr/bin/env node
// Generates `src/latex_tables.rs` from `packages/tui/src/latex.ts`.
//
// The symbol maps and command sets are transcribed mechanically so no entry can
// be mistyped: each literal is evaluated in Node and emitted as a Rust table.

import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "/Users/dev/projects/notagent-main/packages/tui/src/latex.ts";
const OUTPUT = new URL("../src/latex_tables.rs", import.meta.url);

const source = readFileSync(SOURCE, "utf8");

/** Slice the literal that follows `const <name> =` and evaluate it. */
function literal(name) {
	const marker = `const ${name}`;
	const start = source.indexOf(marker);
	if (start < 0) throw new Error(`missing ${name}`);
	const assign = source.indexOf("=", start);
	let index = source.indexOf(assign);
	// Find the first bracket after the assignment.
	let open = -1;
	for (let i = assign; i < source.length; i++) {
		if (source[i] === "{" || source[i] === "[") {
			open = i;
			break;
		}
	}
	const closing = source[open] === "{" ? "}" : "]";
	let depth = 0;
	let end = -1;
	let inString = null;
	for (index = open; index < source.length; index++) {
		const character = source[index];
		if (inString) {
			if (character === "\\") index++;
			else if (character === inString) inString = null;
			continue;
		}
		if (character === '"' || character === "'" || character === "`") {
			inString = character;
			continue;
		}
		if (character === "{" || character === "[") depth++;
		if (character === "}" || character === "]") {
			depth--;
			if (depth === 0) {
				end = index;
				break;
			}
		}
	}
	if (end < 0) throw new Error(`unterminated literal for ${name}`);
	const text = source.slice(open, end + 1);
	// eslint-disable-next-line no-eval
	return eval(`(${text})`);
}

function rustString(value) {
	return JSON.stringify(value);
}

function emitMap(name, object, doc) {
	const entries = Object.entries(object)
		.map(([key, value]) => `    (${rustString(key)}, ${rustString(value)}),`)
		.join("\n");
	return `/// ${doc}\npub static ${name}: &[(&str, &str)] = &[\n${entries}\n];\n`;
}

function emitSet(name, values, doc) {
	const entries = [...values].map((value) => `    ${rustString(value)},`).join("\n");
	return `/// ${doc}\npub static ${name}: &[&str] = &[\n${entries}\n];\n`;
}

const parts = [
	"//! GENERATED by `tools/gen-latex-tables.mjs` — do not edit.\n//!\n//! Symbol maps and command sets of `packages/tui/src/latex.ts`.\n",
	emitMap("SYMBOLS", literal("SYMBOLS"), "`SYMBOLS`: command name to Unicode symbol."),
	emitSet("NAMED_OPERATORS", literal("NAMED_OPERATORS"), "`NAMED_OPERATORS`."),
	emitSet("LIMIT_OPERATORS", literal("LIMIT_OPERATORS"), "`LIMIT_OPERATORS`."),
	emitSet("DISPLAY_LIMIT_SYMBOLS", literal("DISPLAY_LIMIT_SYMBOLS"), "`DISPLAY_LIMIT_SYMBOLS`."),
	emitSet("RELATION_COMMANDS", literal("RELATION_COMMANDS"), "`RELATION_COMMANDS`."),
	emitMap("NEGATED_SYMBOLS", literal("NEGATED_SYMBOLS"), "`NEGATED_SYMBOLS`."),
	emitMap("BLACKBOARD", literal("BLACKBOARD"), "`BLACKBOARD`."),
	emitMap("SUPERSCRIPTS", literal("SUPERSCRIPTS"), "`SUPERSCRIPTS`."),
	emitMap("SUBSCRIPTS", literal("SUBSCRIPTS"), "`SUBSCRIPTS`."),
	emitSet("SPACING_COMMANDS", literal("SPACING_COMMANDS"), "`SPACING_COMMANDS`."),
	emitSet(
		"NEGATIVE_SPACING_COMMANDS",
		literal("NEGATIVE_SPACING_COMMANDS"),
		"`NEGATIVE_SPACING_COMMANDS`.",
	),
	emitSet("IGNORED_COMMANDS", literal("IGNORED_COMMANDS"), "`IGNORED_COMMANDS`."),
	emitSet("SIZE_COMMANDS", literal("SIZE_COMMANDS"), "`SIZE_COMMANDS`."),
	emitSet("PLAIN_WRAPPERS", literal("PLAIN_WRAPPERS"), "`PLAIN_WRAPPERS`."),
	emitMap("ACCENTS", literal("ACCENTS"), "`ACCENTS`."),
];

writeFileSync(OUTPUT, parts.join("\n"));
console.log(`wrote ${OUTPUT.pathname}`);
